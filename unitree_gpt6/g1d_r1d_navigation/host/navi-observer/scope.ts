/**
 * scope.ts -- decides whether a session is a Navi session (pure functions, no DSH dependency, `node --test`-able).
 *
 * Why: navi-observer is a host-layer plugin and sees every session in the process. When a DSH instance also hosts
 * someone's coding session, the plugin must never push "robot has stopped" into it.
 *
 * Two reliable signals (both at the session-assembly layer, independent of session content):
 *   1. preset is `navi` -- under the web profile every session is assembled from an agent preset. start.sh generates
 *      the navi preset (config.id: navi) from host/navi-persona-<g1d|r1d>.txt and makes it the registry default.
 *      This is the only reliable signal under web.
 *   2. the system prompt contains the Navi persona marker -- headless has no presets; the persona is rendered into
 *      the system prompt via deployment-level system-prompt.personaPrefix (also from host/navi-persona-<g1d|r1d>.txt).
 *      Note: in this DSH version requestHeader().system is always undefined, so this path is inactive; headless
 *      support needs systemText from the system/message event instead (see index.ts; known limitation, not implemented).
 *
 * Why not tool names: the mcp-robot row is mounted at the host layer, so `mcp__robot__*` appears in the tool list of
 * **every** session (presets need not mount it again); using it would misclassify coding sessions as Navi sessions.
 */

/** Preset id of Navi sessions under the web profile (= config.id in the preset generated by start.sh). */
export const NAVI_PRESET = "navi";

/** Fixed phrase in the Navi persona (first line of host/navi-persona-<g1d|r1d>.txt), used for headless detection. */
export const NAVI_SYSTEM_MARKER = "Unitree Navi Agent";

export interface SessionProbe {
  /** agent.session.header.agentPreset, or the latest agent-preset/selected in the session log. */
  presetId?: string | null;
  /** Assembled system prompt (agent.session.requestHeader()?.system). */
  systemText?: string | null;
}

/** Either assembly-layer signal marks a Navi session. */
export function isNaviSession(probe: SessionProbe): boolean {
  if (probe.presetId === NAVI_PRESET) return true;
  const text = probe.systemText;
  return typeof text === "string" && text.includes(NAVI_SYSTEM_MARKER);
}

/** Minimal session-log event shape (only the two fields we read). */
export interface PresetEventLike {
  type?: string;
  data?: { agentPreset?: unknown };
}

/**
 * Latest `agent-preset/selected` from the session log.
 * Web sessions append this event when mounting a preset (before this plugin's first poll), so we do not rely on
 * `header.agentPreset` (only set for webhook-style creation).
 * @returns preset id; null if no selection was recorded.
 */
export function presetFromLog(events: readonly PresetEventLike[]): string | null {
  for (let i = events.length - 1; i >= 0; i -= 1) {
    const event = events[i];
    if (event?.type !== "agent-preset/selected") continue;
    const id = event.data?.agentPreset;
    if (typeof id === "string" && id.length > 0) return id;
  }
  return null;
}
